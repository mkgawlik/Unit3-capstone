from __future__ import annotations

import json
import os
import threading
import uuid
from collections import defaultdict
from contextvars import ContextVar
from datetime import datetime, timezone


PRICING = {
    "haiku": {"input": 1.00, "output": 5.00},
    "sonnet": {"input": 3.00, "output": 15.00},
    "opus": {"input": 5.00, "output": 25.00},
}

CALLS = []
QUERIES = {}
LOCK = threading.Lock()
CURRENT_QUERY_ID = ContextVar("current_query_id", default=None)


def _rates() -> tuple[float, float]:
    tier = os.getenv("CLAUDE_PRICING_TIER", "sonnet").lower()
    defaults = PRICING.get(tier, PRICING["sonnet"])

    input_rate = float(
        os.getenv("CLAUDE_INPUT_USD_PER_MILLION", defaults["input"])
    )
    output_rate = float(
        os.getenv("CLAUDE_OUTPUT_USD_PER_MILLION", defaults["output"])
    )

    return input_rate, output_rate


def calculate_cost(input_tokens: int, output_tokens: int) -> float:
    input_rate, output_rate = _rates()

    return (
        (input_tokens / 1_000_000) * input_rate
        + (output_tokens / 1_000_000) * output_rate
    )


def start_query(question: str) -> str:
    query_id = f"q-{uuid.uuid4().hex[:10]}"

    with LOCK:
        QUERIES[query_id] = {
            "question": question,
            "started_at": datetime.now(timezone.utc).isoformat(),
        }

    CURRENT_QUERY_ID.set(query_id)
    return query_id


def log_claude_call(
    component: str,
    input_tokens: int,
    output_tokens: int,
    model_id: str | None = None,
    query_id: str | None = None,
) -> dict:
    query_id = query_id or CURRENT_QUERY_ID.get() or "untracked"
    cost = calculate_cost(input_tokens, output_tokens)

    record = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "query_id": query_id,
        "component": component,
        "model_id": model_id or os.getenv("BEDROCK_MODEL_ID", "configured-model"),
        "input_tokens": int(input_tokens),
        "output_tokens": int(output_tokens),
        "total_tokens": int(input_tokens) + int(output_tokens),
        "cost_usd": round(cost, 8),
    }

    with LOCK:
        CALLS.append(record)

    print(
        f"[TOKENOMICS] query={query_id} "
        f"component={component} "
        f"input={record['input_tokens']} "
        f"output={record['output_tokens']} "
        f"cost_usd=${record['cost_usd']:.8f}"
    )

    try:
        log_file = os.getenv("TOKENOMICS_LOG_FILE", "tokenomics_log.jsonl")
        with open(log_file, "a", encoding="utf-8") as file:
            file.write(json.dumps(record) + "\n")
    except OSError:
        pass

    return record


def finish_query(query_id: str) -> dict:
    with LOCK:
        QUERIES[query_id]["finished_at"] = datetime.now(
            timezone.utc
        ).isoformat()

    return query_summary(query_id)


def query_summary(query_id: str) -> dict:
    with LOCK:
        query = dict(QUERIES.get(query_id, {}))
        calls = [dict(call) for call in CALLS if call["query_id"] == query_id]

    component_totals = defaultdict(
        lambda: {"input_tokens": 0, "output_tokens": 0, "cost_usd": 0.0}
    )

    for call in calls:
        component = component_totals[call["component"]]
        component["input_tokens"] += call["input_tokens"]
        component["output_tokens"] += call["output_tokens"]
        component["cost_usd"] += call["cost_usd"]

    total_input = sum(call["input_tokens"] for call in calls)
    total_output = sum(call["output_tokens"] for call in calls)
    total_cost = sum(call["cost_usd"] for call in calls)

    return {
        **query,
        "query_id": query_id,
        "calls": calls,
        "components": dict(component_totals),
        "input_tokens": total_input,
        "output_tokens": total_output,
        "total_tokens": total_input + total_output,
        "cost_usd": round(total_cost, 8),
    }


def run_traced_query(orchestrator, question: str) -> dict:
    query_id = start_query(question)

    initial_state = {
        "question": question,
        "route": None,
        "sql_result": None,
        "retrieval_result": None,
        "final_answer": None,
        "token_usage": None,
    }

    try:
        result = orchestrator.invoke(initial_state)
    finally:
        summary = finish_query(query_id)

    return {
        **result,
        "tokenomics_query_id": query_id,
        "tokenomics_summary": summary,
    }


def print_summary_table() -> None:
    with LOCK:
        query_ids = list(QUERIES.keys())

    print("\n10-QUERY TOKENOMICS SUMMARY")
    print("-" * 92)
    print(
        f"{'Query':<14}{'Input':>12}{'Output':>12}"
        f"{'Total Tokens':>16}{'Cost USD':>16}"
    )

    for query_id in query_ids:
        summary = query_summary(query_id)
        print(
            f"{query_id:<14}"
            f"{summary['input_tokens']:>12,}"
            f"{summary['output_tokens']:>12,}"
            f"{summary['total_tokens']:>16,}"
            f"${summary['cost_usd']:>15.8f}"
        )

    component_totals = defaultdict(
        lambda: {"tokens": 0, "cost_usd": 0.0}
    )

    with LOCK:
        all_calls = list(CALLS)

    for call in all_calls:
        component = component_totals[call["component"]]
        component["tokens"] += call["total_tokens"]
        component["cost_usd"] += call["cost_usd"]

    print("\nCOMPONENT TOTALS")
    print("-" * 60)

    for component, values in sorted(
        component_totals.items(),
        key=lambda item: item[1]["tokens"],
        reverse=True,
    ):
        print(
            f"{component:<32}"
            f"{values['tokens']:>14,} tokens  "
            f"${values['cost_usd']:.8f}"
        )

    if component_totals:
        largest = max(
            component_totals,
            key=lambda component: component_totals[component]["tokens"],
        )
        print(f"\nMost tokens consumed by: {largest}")

    print(f"Queries run: {len(query_ids)}")


SQL_KEYWORDS = [
    "how many",
    "count",
    "total",
    "average",
    "sum",
    "revenue",
    "how much",
    "list all",
    "which clients",
    "projects",
    "invoices",
    "consultants",
    "compare",
    "trend",
    "budget",
]

DOC_KEYWORDS = [
    "policy",
    "process",
    "procedure",
    "methodology",
    "what is",
    "explain",
    "describe",
    "guidelines",
    "approach",
    "onboarding",
]


def route_question_logged(state: dict) -> dict:
    question = state["question"].lower()
    is_sql = any(keyword in question for keyword in SQL_KEYWORDS)
    is_doc = any(keyword in question for keyword in DOC_KEYWORDS)

    if is_sql and is_doc:
        route = "both"
    elif is_sql:
        route = "sql"
    else:
        route = "retrieval"

    return {**state, "route": route}


def _normalise_usage(usage: dict | None) -> dict:
    usage = usage or {}

    return {
        "input": int(
            usage.get("input", usage.get("input_tokens", 0)) or 0
        ),
        "output": int(
            usage.get("output", usage.get("output_tokens", 0)) or 0
        ),
    }


def calculate_full_query_cost(
    sql_tokens: dict | None = None,
    retrieval_tokens: dict | None = None,
    synthesis_tokens: dict | None = None,
    classification_tokens: dict | None = None,
) -> dict:
    usages = {
        "sql": _normalise_usage(sql_tokens),
        "retrieval": _normalise_usage(retrieval_tokens),
        "synthesis": _normalise_usage(synthesis_tokens),
        "classification": _normalise_usage(classification_tokens),
    }

    components = {}

    for name, usage in usages.items():
        components[name] = {
            "input_tokens": usage["input"],
            "output_tokens": usage["output"],
            "total_tokens": usage["input"] + usage["output"],
            "cost_usd": round(
                calculate_cost(usage["input"], usage["output"]),
                8,
            ),
        }

    total_tokens = sum(
        component["total_tokens"] for component in components.values()
    )
    total_cost = sum(
        component["cost_usd"] for component in components.values()
    )

    largest_component = max(
        components,
        key=lambda name: components[name]["total_tokens"],
    )

    return {
        "components": components,
        "total_tokens": total_tokens,
        "total_cost_usd": round(total_cost, 8),
        "most_tokens_component": largest_component,
    }
